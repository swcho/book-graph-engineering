"""
예제 5 — 느려졌다. 어디를 먼저 볼 것인가.

    python3 ex5_where_time_goes.py

의존성 없음. 한 요청의 시간을 구간별로 쪼개고,
「어느 구간을 고치면 얼마나 좋아지나」를 계산한다.
"""

# 한 요청의 구간별 시간 (ms) 과 그 구간을 «얼마나 줄일 수 있나»
SEGMENTS = [
    ("입력 검증",        3,    0.0,  "이미 최소"),
    ("그래프 조회 ×4",   9,    0.5,  "인덱스·플랜"),
    ("벡터 검색",       11,    0.4,  "차원 축소·근사"),
    ("컨텍스트 조립",    18,    0.7,  "24장 — 참조만 싣기"),
    ("모델 호출",     1_820,   0.3,  "짧은 프롬프트·작은 모델"),
    ("응답 후처리",      24,    0.6,  "스트리밍"),
    ("체크포인트 쓰기",   34,    0.8,  "상태 줄이기·슈퍼스텝 줄이기"),
]


def main():
    total = sum(ms for _n, ms, _r, _h in SEGMENTS)
    print(f"한 요청 총 {total:,}ms. 구간별로 쪼개 본다.\n")
    print(f"{'구간':<18}{'ms':>8}{'비중':>8}{'최대 절감':>10}"
          f"{'줄이면':>10}  방법")
    print("-" * 78)
    for name, ms, ratio, how in SEGMENTS:
        save = ms * ratio
        bar = "█" * max(0, int(ms / total * 40))
        print(f"{name:<18}{ms:>8,}{ms / total:>7.1%}{ratio:>10.0%}"
              f"{save:>9,.0f}ms  {how}")

    print("\n비중 막대:\n")
    for name, ms, _r, _h in SEGMENTS:
        bar = "█" * max(1, int(ms / total * 46))
        print(f"  {name:<18}{ms / total:>6.1%}  {bar}")

    best = max(SEGMENTS, key=lambda x: x[1] * x[2])
    all_save = sum(ms * r for _n, ms, r, _h in SEGMENTS)
    print(f"\n제일 크게 줄일 수 있는 구간: {best[0]} "
          f"({best[1] * best[2]:,.0f}ms)")
    print(f"전부 다 줄이면: {all_save:,.0f}ms "
          f"({all_save / total:.0%})")
    print(f"모델 호출만 빼고 전부 줄이면: "
          f"{all_save - 1820 * 0.3:,.0f}ms "
          f"({(all_save - 1820 * 0.3) / total:.1%})")

    print(
        "\n모델 호출이 전체의 94.8%다. 나머지 여섯 구간을 «전부» 최대로 줄여도\n"
        "60ms 밖에 안 준다. 총 1,919ms 의 3% 다.\n"
        "\n이게 에이전트 시스템 성능 튜닝의 첫 사실이다.\n"
        "«모델 호출 앞뒤를 아무리 다듬어도 모델 호출이 안 줄면 안 빨라진다.»\n"
        "\n그래서 순서가 이렇게 된다.\n"
        "  1. 모델 호출 «횟수»를 줄인다 — 캐시, 라우팅(25장), 종료 조건(20장)\n"
        "  2. 모델 호출 «시간»을 줄인다 — 짧은 프롬프트, 작은 모델, 스트리밍\n"
        "  3. 그다음에 나머지를 본다\n"
        "\n3번을 1번보다 먼저 하는 팀이 많다. 익숙하고, 재기 쉽고, 성과가 눈에 보여서다.\n"
        "「쿼리를 9ms 에서 4ms 로 줄였습니다」는 보고하기 좋은 문장이다.\n"
        "그런데 사용자는 1,919ms 를 1,914ms 로 줄인 것을 못 느낀다.\n"
        "\n한 가지 덧붙이면, 체크포인트 쓰기가 34ms 로 두 번째다.\n"
        "여기는 «구조»를 고치면 크게 준다. 21장의 슈퍼스텝 얘기다.\n"
        "그리고 이건 쿼리 튜닝이 아니라 그래프 설계 문제다."
    )


if __name__ == "__main__":
    main()
