"""
예제 4 — 느린 쿼리 하나보다 «자주 도는 쿼리»가 아프다.

    python3 ex4_hot_query.py

의존성 없음. 쿼리별 지연과 호출 수를 곱해서 «총 시간»으로 줄 세운다.
"""

QUERIES = [
    # 이름                    1회 ms   하루 호출 수
    ("팀 구성원 조회",            2.1,   4_200_000),
    ("2홉 이웃 탐색",           18.0,     140_000),
    ("전체 조직도 렌더",        820.0,       1_400),
    ("사용자 권한 계산",          3.4,   2_800_000),
    ("월간 감사 리포트",      12_000.0,          30),
    ("이름으로 사람 찾기",        1.2,   6_100_000),
    ("커뮤니티 탐지",         31_000.0,           2),
]


def main():
    print("쿼리 일곱 개. 「제일 느린 것」과 「제일 아픈 것」이 다르다.\n")

    by_latency = sorted(QUERIES, key=lambda q: -q[1])
    print("[1회 지연 순]")
    for name, ms, n in by_latency[:4]:
        print(f"    {name:<20}{ms:>12,.1f} ms")

    rows = [(name, ms, n, ms * n / 1000 / 3600) for name, ms, n in QUERIES]
    by_total = sorted(rows, key=lambda r: -r[3])
    total = sum(r[3] for r in rows)

    print("\n[하루 총 시간 순]")
    print(f"    {'쿼리':<20}{'1회 ms':>12}{'하루 호출':>14}"
          f"{'하루 총 시간':>14}{'비중':>8}")
    print("    " + "-" * 70)
    for name, ms, n, hours in by_total:
        bar = "█" * int(hours / total * 30)
        print(f"    {name:<20}{ms:>12,.1f}{n:>14,}{hours:>12,.1f}h"
              f"{hours / total:>7.0%}  {bar}")

    print(f"\n    {'합계':<20}{'':<26}{total:>12,.1f}h")

    print(
        "\n제일 느린 것은 «커뮤니티 탐지»다. 31초 걸린다.\n"
        "그런데 하루에 두 번 돈다. 총 시간은 0.02시간이다.\n"
        "\n제일 아픈 것은 «사용자 권한 계산»이다. 3.4ms 밖에 안 걸리는데\n"
        "하루 280만 번 돌아서 총 2.6시간, 전체의 32%다.\n"
        "\n상위 셋(권한 계산·팀 구성원·이름 찾기)이 전체의 87%를 먹는다.\n"
        "셋 다 «빠른» 쿼리다. 1~3ms 짜리들이다.\n"
        "\n권한 계산을 3.4ms 에서 1.7ms 로 줄이면 하루 1.3시간이 준다.\n"
        "커뮤니티 탐지를 31초에서 15초로 줄이면 하루 0.00003시간이 준다.\n"
        "\n그래서 튜닝 순서는 «느린 것»이 아니라 «총 시간이 큰 것»이다.\n"
        "그리고 이 둘은 대개 다르다.\n"
        "\n느린 쿼리 로그(slow query log)의 함정이 여기 있다.\n"
        "임계값을 100ms 로 잡으면 1.2ms 짜리는 «한 번도 안 찍힌다».\n"
        "제일 아픈 쿼리가 로그에 아예 안 나온다.\n"
        "\n그래서 봐야 할 지표는 «p99 지연»만이 아니라 «쿼리별 총 시간»이다.\n"
        "  느린 쿼리 로그  → 사용자가 «기다린다»고 느끼는 것을 찾는다\n"
        "  총 시간 순위    → 인프라를 «먹는» 것을 찾는다\n"
        "\n둘 다 봐야 하고, 고치는 순서는 대개 후자가 먼저다."
    )


if __name__ == "__main__":
    main()
