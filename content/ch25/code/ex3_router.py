"""
예제 3 — 라우터(동적 엣지)가 틀리면 어떻게 되나.

    python3 ex3_router.py

의존성 없음. 라우팅 정확도를 바꿔 가며
«전부 비싼 길로 보내기»와 비교한다.
"""

# 길 이름     비용   이 길이 «맞을 때» 품질   «틀린 길로 왔을 때» 품질
ROUTES = {
    "빠른 길":   (1_200, 0.86, 0.42),
    "정밀한 길": (7_400, 0.93, 0.88),
}
MIX = {"빠른 길": 0.72, "정밀한 길": 0.28}   # 실제 입력의 분포
N = 1_000


def all_precise():
    cost = N * ROUTES["정밀한 길"][0]
    q = sum(MIX[k] * (ROUTES["정밀한 길"][1] if k == "정밀한 길"
                      else ROUTES["정밀한 길"][2]) for k in MIX)
    return cost, q


def routed(acc):
    cost = q = 0.0
    for true_route, share in MIX.items():
        n = N * share
        for taken, p in ((true_route, acc), (other(true_route), 1 - acc)):
            c, right, wrong = ROUTES[taken]
            cost += n * p * c
            q += share * p * (right if taken == true_route else wrong)
    return cost, q


def other(k):
    return "정밀한 길" if k == "빠른 길" else "빠른 길"


def main():
    print(f"입력 {N}건. 72%는 빠른 길로 충분하고 28%는 정밀한 길이 필요하다.\n")
    pc, pq = all_precise()
    print(f"{'방식':<26}{'총 토큰':>12}{'평균 품질':>10}{'절감':>9}")
    print("-" * 58)
    print(f"{'전부 정밀한 길':<26}{pc:>12,.0f}{pq:>10.3f}{'-':>9}")
    for acc in (1.00, 0.95, 0.90, 0.80, 0.70, 0.50):
        c, q = routed(acc)
        print(f"{f'라우팅 (정확도 {acc:.0%})':<26}{c:>12,.0f}{q:>10.3f}"
              f"{1 - c / pc:>8.0%}")

    print(
        "\n제가 기대한 건 «라우팅이 완벽하면 품질도 오른다»였다. 안 올랐다.\n"
        "정확도 100%에서도 품질이 0.894 에서 0.880 으로 내려간다.\n"
        "\n이유는 표를 만들 때 넣은 가정에 있다.\n"
        "정밀한 길은 «굳이 안 써도 되는 입력»에도 0.88 을 낸다. 빠른 길의 0.86 보다 높다.\n"
        "즉 이 설정에서는 정밀한 길이 언제나 품질로는 이긴다.\n"
        "\n그러니 라우팅은 품질을 «올리는» 장치가 아니다. 품질을 조금 내주고\n"
        "토큰을 크게 아끼는 «교환»이다. 100% 정확도에서 품질 1.4%p 를 내주고 60% 를 아낀다.\n"
        "\n이 교환이 남는 장사인지는 도메인이 정한다.\n"
        "품질 1.4%p 가 사람 눈에 안 보이는 서비스면 남는 장사고,\n"
        "그 1.4%p 가 오답 14건이 되는 서비스면 아니다.\n"
        "\n정확도 50% 까지 내려가면 품질 8%p 를 내주고 42% 를 아낀다. 이건 대개 손해다.\n"
        "라우터 정확도를 모르면 이 교환을 계산할 수 없고,\n"
        "계산 못 하면 «라우터 넣었더니 좋아졌다»는 느낌만 남는다.\n"
        "\n그래서 라우터를 넣을 때 제일 먼저 만들 것은 라우터가 아니라\n"
        "«라우팅이 맞았는지 채점하는 데이터셋»이다. 100건이면 시작할 수 있다."
    )


if __name__ == "__main__":
    main()
