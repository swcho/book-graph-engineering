"""
예제 3 — 무엇이 살아남나. 지난 30년의 기술을 놓고 세어 본다.

    python3 ex3_what_survives.py

의존성 없음. 「이름」과 「문제」와 「해법」을 나눠서 본다.
셋의 수명이 다르다.
"""

ITEMS = [
    # (이름, 등장, 지금 상태, 종류)
    ("전문가 시스템",       1980, "이름은 사라짐",   "이름"),
    ("시맨틱 웹",          2001, "이름은 흐려짐",   "이름"),
    ("빅데이터",           2010, "이름은 사라짐",   "이름"),
    ("마이크로서비스",       2014, "이름은 남음",     "이름"),
    ("프롬프트 엔지니어링",   2022, "이름이 옮겨감",   "이름"),

    ("지식을 명시적으로 적기", 1970, "지금도 문제",    "문제"),
    ("무엇이 언제 참이었나",   1980, "지금도 문제",    "문제"),
    ("어디서 온 정보인가",    1990, "지금도 문제",    "문제"),
    ("동시 변경 충돌",       1975, "지금도 문제",    "문제"),
    ("무엇을 잊을 것인가",    1985, "지금도 문제",    "문제"),

    ("규칙 기반 추론",       1975, "일부만 남음",    "해법"),
    ("이시간 모델",         1990, "그대로 씀",      "해법"),
    ("낙관적 잠금",         1979, "그대로 씀",      "해법"),
    ("이벤트 소싱",         2005, "그대로 씀",      "해법"),
    ("진리 유지 시스템",      1979, "다시 필요해짐",   "해법"),
    ("복식부기",           1494, "그대로 씀",      "해법"),
]

NOW = 2026


def main():
    print("지난 30년(그리고 500년)의 것들을 세 종류로 나눠 본다.\n")
    for kind in ("이름", "문제", "해법"):
        rows = [i for i in ITEMS if i[3] == kind]
        ages = [NOW - i[1] for i in rows]
        print(f"[{kind}]  평균 나이 {sum(ages) / len(ages):.0f}년")
        for name, year, state, _k in sorted(rows, key=lambda x: x[1]):
            print(f"    {year}  {name:<24}{state}")
        print()

    survived = sum(1 for i in ITEMS if i[3] == "이름" and "남음" in i[2])
    print(f"«이름» 다섯 중 지금도 그대로 쓰는 것: {survived}개")
    print(f"«문제» 다섯 중 지금도 문제인 것: "
          f"{sum(1 for i in ITEMS if i[3] == '문제')}개")

    print(
        "\n이름은 사라지고, 문제는 남고, 해법은 이름을 바꿔 가며 재사용된다.\n"
        "\n«복식부기»가 이 표에서 제일 오래됐다. 532년이다.\n"
        "그리고 30장의 이벤트 소싱이 그것과 같은 구조다.\n"
        "「지우지 말고 반대 기입을 하라」가 「이벤트를 쌓아라」가 됐을 뿐이다.\n"
        "\n«진리 유지 시스템»은 1979년에 나왔다가 한동안 잊혔다.\n"
        "딥러닝 시대에는 필요 없었다. 신경망은 «왜 그렇게 생각했나»를 못 대니\n"
        "철회할 것도 없었다. 에이전트가 그래프에 쓰기 시작하니 다시 필요해졌다.\n"
        "\n그래서 이 책을 읽고 가져가실 것을 순서로 매기면 이렇다.\n"
        "  1. 문제  — 30년 뒤에도 그대로 있을 것\n"
        "  2. 해법  — 이름이 바뀌어도 구조는 남을 것\n"
        "  3. 이름  — 내년에 없을 수도 있는 것\n"
        "\n이 책은 3번을 제목에 걸고 있다. 그건 어쩔 수 없다.\n"
        "다만 안에 들어 있는 것은 1번과 2번이기를 바라며 썼다."
    )


if __name__ == "__main__":
    main()
