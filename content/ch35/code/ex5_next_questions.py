"""
예제 5 — 이 책이 못 답한 것들. 각 장의 「내가 아직 모르는 것」을 모은다.

    python3 ex5_next_questions.py

의존성 없음. 미해결 질문을 종류별로 묶고, 「누가 풀 것인가」를 붙인다.
"""

OPEN = [
    ("추출 근거를 모델에게 물어서 받은 답이 맞는지 확인할 방법",
     "28장", "연구", "높음"),
    ("그래프의 «구조적» 익명화 — 관계 모양으로 특정되는 것을 막기",
     "34장", "연구", "높음"),
    ("의미가 바뀌는 스키마 변경(이름은 그대로, 뜻이 달라짐)",
     "32장", "실무", "중간"),
    ("모호한 사실을 그래프에 담는 법 — 확신도 숫자의 근거",
     "27장", "연구", "중간"),
    ("자동 병합 오류율을 허용할 수 있는 기준",
     "31장", "실무", "중간"),
    ("에이전트가 스키마 변경을 스스로 하게 하기",
     "32장", "실무", "낮음"),
    ("조회가 나빠서 모델을 한 번 더 부른 경우를 세는 법",
     "33장", "실무", "중간"),
    ("종류별 비율 상한·하한을 도메인마다 정하는 원칙",
     "28장", "실무", "낮음"),
    ("여러 마이그레이션이 동시에 돌 때 불일치의 원인 구분",
     "32장", "실무", "낮음"),
    ("샤딩된 이벤트 로그에서 전역 순서 정하기",
     "30장", "연구", "중간"),
    ("승인 피로를 재는 지표",
     "23장", "연구", "낮음"),
    ("성숙한 온톨로지를 에이전트 도구 카탈로그로 쓰는 법",
     "25·29장", "실무", "중간"),
]


def main():
    print(f"이 책의 「내가 아직 모르는 것」 상자에서 모은 {len(OPEN)}개.\n")

    for kind in ("연구", "실무"):
        rows = [o for o in OPEN if o[2] == kind]
        print(f"[{kind}가 풀 것] {len(rows)}개")
        for q, ch, _k, w in sorted(rows, key=lambda x: {"높음": 0, "중간": 1,
                                                        "낮음": 2}[x[3]]):
            print(f"    ({w:<2}) {q}")
            print(f"          {ch}")
        print()

    high = [o for o in OPEN if o[3] == "높음"]
    print(f"제일 급한 것 {len(high)}개는 전부 «연구»다.")
    for q, ch, _k, _w in high:
        print(f"    {q}  ({ch})")

    print(
        "\n두 개가 눈에 띈다. 둘 다 «에이전트가 만든 것을 검증하는» 문제다.\n"
        "\n  - 추출 근거가 진짜 근거인지 확인하기 (28장)\n"
        "  - 관계 모양으로 특정되는 것을 막기 (34장)\n"
        "\n앞의 것은 «모델이 자기 판단 과정을 정직하게 말하는가»이고\n"
        "뒤의 것은 «구조 자체가 정보를 흘리는가»다.\n"
        "\n그리고 둘 다 제가 못 풀 문제다. 논문이 나와야 한다.\n"
        "\n나머지 여덟은 실무 문제고, 시간과 사례가 쌓이면 답이 나올 것이다.\n"
        "그중 몇 개는 이미 누군가 풀었는데 제가 모르는 것일 수도 있다.\n"
        "\n이 목록을 마지막 예제로 둔 이유가 있다.\n"
        "책이 답을 다 주는 것처럼 끝나면 안 될 것 같아서다.\n"
        "이 분야는 그럴 만큼 자리를 잡지 않았다."
    )


if __name__ == "__main__":
    main()
