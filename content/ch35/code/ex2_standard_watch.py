"""
예제 2 — 표준이 어디까지 왔나. 그리고 무엇을 지켜볼 것인가.

    python3 ex2_standard_watch.py

의존성 없음. 이 책에서 [표준]/[업계 표준]/[실험] 로 표시한 것들이
지금 어느 단계에 있는지 정리한다. 확인 시점 2026년 8월.
"""

STAGES = ["아이디어", "구현이 여럿", "명세 초안", "공식 명세", "널리 채택"]

ITEMS = [
    # 이름                        단계   이 책 표시   지켜볼 신호
    ("RDF · OWL · SHACL",          4, "표준",
     "이미 안정. 큰 변화 없을 것"),
    ("SPARQL 1.1",                 4, "표준",
     "1.2 작업이 진행 중"),
    ("ISO GQL",                    3, "표준",
     "엔진들이 실제로 구현하는지"),
    ("SQL/PGQ",                    3, "표준",
     "DuckDB · 상용 DB 의 지원 범위"),
    ("Cypher 방언",                1, "업계 표준",
     "GQL 로 수렴하는지, 갈라지는지"),
    ("MCP",                        2, "업계 표준",
     "명세 버전이 얼마나 자주 바뀌는지"),
    ("PROV-O",                     4, "표준",
     "에이전트 계보에 실제로 쓰이는지"),
    ("GraphRAG 계열",              1, "업계 표준",
     "공통 평가 기준이 생기는지"),
    ("에이전트 간 프로토콜",         1, "실험",
     "구현이 둘 이상 상호운용되는지"),
    ("에이전트 그래프 위상 이론",     0, "실험",
     "논문에 공통 용어가 생기는지"),
    ("그래프 기반 장기 기억",        1, "실험",
     "벤치마크가 생기는지"),
    ("자기수정 온톨로지",           0, "실험",
     "운영 사례가 공개되는지"),
]


def main():
    print(f"확인 시점 2026년 8월. 단계: {' → '.join(STAGES)}\n")
    print(f"{'항목':<26}{'단계':<12}{'표시':<12}지켜볼 신호")
    print("-" * 88)
    for name, stage, tag, watch in sorted(ITEMS, key=lambda x: -x[1]):
        dots = "●" * (stage + 1) + "○" * (4 - stage)
        print(f"{name:<26}{dots:<12}{tag:<12}{watch}")

    counts = {}
    for _n, _s, tag, _w in ITEMS:
        counts[tag] = counts.get(tag, 0) + 1
    print(f"\n표시별 개수: {counts}")

    exp = [i for i in ITEMS if i[2] == "실험"]
    print(f"\n[실험] {len(exp)}개의 평균 단계: "
          f"{sum(i[1] for i in exp) / len(exp):.1f} / 4")

    print(
        "\n[표준] 과 [실험] 사이가 비어 있는 게 이 표의 요점이다.\n"
        "\n[표준] 다섯은 전부 W3C 나 ISO 것이고, 트랙 1(지식 그래프) 쪽이다.\n"
        "[실험] 넷은 전부 트랙 2(에이전트) 쪽이고, 평균 단계가 0.5 다.\n"
        "\n그러니까 이 책의 두 트랙은 «성숙도가 20년쯤 차이 난다».\n"
        "그래서 3부는 「이렇게 하면 된다」로 쓸 수 있었고\n"
        "4부는 「저는 이렇게 하는데 확신은 없습니다」로 쓸 수밖에 없었다.\n"
        "\n3년 뒤에 이 표를 다시 그리면 아래쪽 넷이 위로 올라와 있을 수도 있다.\n"
        "안 올라와 있을 수도 있고, 아예 다른 이름으로 바뀌어 있을 수도 있다.\n"
        "\n지켜볼 신호를 적어 둔 게 그래서다.\n"
        "「MCP 명세 버전이 얼마나 자주 바뀌는지」 같은 건 링크 하나 열면 5분에 확인된다.\n"
        "그리고 그 5분이 「지금 이걸 도입해도 되나」의 답을 준다."
    )


if __name__ == "__main__":
    main()
