WEEKS = [
    # (주차, 전체 노드, 차단 위반, 경고, 기록, 필수속성 채움률, 링크 유효율)
    (1,  12_000,  40, 210,  980, 0.94, 0.99),
    (2,  18_000,  38, 260, 1420, 0.93, 0.99),
    (3,  26_000,  35, 340, 2100, 0.92, 0.98),
    (4,  41_000,  33, 520, 3350, 0.91, 0.98),
    (5,  63_000,  31, 810, 5200, 0.90, 0.97),
    (6, 102_000,  29, 1310, 8400, 0.89, 0.95),
]


def composite(row):
    """흔히 쓰는 «품질 점수» — 위반율을 뒤집어 100점 만점으로."""
    _, n, blk, warn, info, fill, link = row
    bad = blk * 10 + warn * 3 + info
    return max(0.0, 100 * (1 - bad / (n * 0.5)))


def main():
    print(f"{'주':>3} {'노드':>9} {'차단':>6} {'경고':>7} {'기록':>7} "
          f"{'채움률':>7} {'링크':>7} {'종합점수':>9}")
    print("-" * 66)
    for r in WEEKS:
        w, n, blk, warn, info, fill, link = r
        print(f"{w:>3} {n:>9,} {blk:>6} {warn:>7,} {info:>7,} "
              f"{fill:>7.2f} {link:>7.2f} {composite(r):>9.1f}")

    print(
        "\n종합 점수만 보면 «좋아지고 있다». 1주 66.5점에서 6주 75.3점.\n"
        "데이터가 늘어난 만큼 위반이 늘었는데 «비율»로 나누니 좋아 보인다.\n"
        "\n따로 보면 다르다.\n"
        "  차단 위반은 40 → 29 로 줄었다. 진짜 좋아졌다.\n"
        "  경고는 210 → 1,310 으로 6배 늘었다. 나빠졌다.\n"
        "  필수 속성 채움률은 0.94 → 0.89. 계속 떨어진다.\n"
        "  링크 유효율은 0.99 → 0.95. 이게 제일 급하다.\n"
        "\n종합 점수는 이 넷을 섞어 버려서 아무것도 못 보게 만든다.\n"
        "\n제 규칙 두 가지.\n"
        "  1. 지표를 하나로 합치지 않는다. 넷이면 넷을 다 보여 준다.\n"
        "  2. 절대 개수와 비율을 «둘 다» 적는다. 하나만 적으면 반드시 속는다."
    )


if __name__ == "__main__":
    main()
