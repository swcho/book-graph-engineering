"""
예제 5 — 참조 아키텍처를 «검사 가능한 형태»로 적는다.

    python3 ex5_reference_arch.py

의존성 없음. 계층과 규칙을 데이터로 적고, 위반을 자동으로 찾는다.
그림으로만 있는 아키텍처는 6개월이면 그림과 코드가 갈라진다.
"""

LAYERS = ["표현", "오케스트레이션", "도메인", "그래프", "저장"]
RANK = {l: i for i, l in enumerate(LAYERS)}

COMPONENTS = {
    "채팅 UI":        ("표현", []),
    "리드 에이전트":   ("오케스트레이션", ["작업자 A", "작업자 B", "승인 게이트"]),
    "작업자 A":       ("오케스트레이션", ["문서 서비스", "그래프 게이트웨이"]),
    "작업자 B":       ("오케스트레이션", ["그래프 게이트웨이"]),
    "승인 게이트":     ("오케스트레이션", ["체크포인트 저장소"]),
    "문서 서비스":     ("도메인", ["객체 저장소"]),
    "그래프 게이트웨이": ("그래프", ["그래프 DB", "벡터 색인"]),
    "쓰기 관문":       ("그래프", ["그래프 DB"]),
    "그래프 DB":      ("저장", []),
    "벡터 색인":       ("저장", []),
    "객체 저장소":     ("저장", []),
    "체크포인트 저장소": ("저장", []),
}

# 규칙 — 그림에 안 적히고 머릿속에만 있던 것들
RULES = [
    ("아래로만 부른다", lambda a, b: RANK[COMPONENTS[b][0]] >= RANK[COMPONENTS[a][0]]),
    ("저장 계층을 건너뛰지 않는다",
     lambda a, b: not (COMPONENTS[a][0] == "오케스트레이션"
                       and COMPONENTS[b][0] == "저장")),
    ("그래프 쓰기는 쓰기 관문을 거친다",
     lambda a, b: not (b == "그래프 DB" and a not in
                       ("그래프 게이트웨이", "쓰기 관문"))),
]


def check():
    bad = []
    for a, (_layer, calls) in COMPONENTS.items():
        for b in calls:
            for name, ok in RULES:
                if not ok(a, b):
                    bad.append((a, b, name))
    return bad


def main():
    print("계층:", " → ".join(LAYERS), "\n")
    print(f"{'구성 요소':<18}{'계층':<16}부르는 것")
    print("-" * 72)
    for name, (layer, calls) in COMPONENTS.items():
        print(f"{name:<18}{layer:<16}{', '.join(calls) or '-'}")

    bad = check()
    print(f"\n규칙 {len(RULES)}개로 검사한 결과: 위반 {len(bad)}건")
    for a, b, why in bad:
        print(f"  ✗ {a} → {b}   ({why})")
    if not bad:
        print("  (없음)")

    print("\n이제 «승인 게이트가 체크포인트 저장소를 직접 부르는» 것을 넣어 본다.")
    print("이미 넣어 뒀다. 위에서 걸렸는지 보시라.\n")

    print(
        "그림으로만 있는 아키텍처는 6개월이면 코드와 갈라진다.\n"
        "다들 겪는 일이고, 다들 «그림을 갱신하자»로 대응한다. 그러면 또 갈라진다.\n"
        "\n대신 이렇게 «검사 가능한 형태»로 적으면 CI 에서 돌릴 수 있다.\n"
        "새 호출을 추가하면서 규칙을 어기면 머지가 안 된다.\n"
        "\n여기 쓴 규칙 셋은 전부 «머릿속에만 있던 것»이다.\n"
        "  - 아래로만 부른다 (순환 의존을 막는다)\n"
        "  - 계층을 건너뛰지 않는다 (오케스트레이터가 저장소를 직접 안 만진다)\n"
        "  - 그래프 쓰기는 관문을 거친다 (28장)\n"
        "\n마지막 규칙이 특히 중요하다. 관문을 만들어 놓고 우회하는 경로가 생기면\n"
        "관문은 있으나 마나가 된다. 그리고 그런 우회는 «급할 때» 생긴다.\n"
        "\n이 파일이 곧 아키텍처 문서다. 그림은 이걸로 «생성»하면 된다.\n"
        "반대로 하면 안 된다. 그림에서 코드를 생성할 수는 없으니까."
    )


if __name__ == "__main__":
    main()
