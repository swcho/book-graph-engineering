"""
예제 1 — 네 가지 종료 조건이 각각 무엇을 잡는가.

    python3 ex1_four_guards.py

의존성 없음.
"""

from guards import Guards

# (설명, 회차별 (비용, 초, 점수)) — 점수는 낮을수록 좋다(위반 건수)
SCENARIOS = {
    "잘 수렴한다":     [(20, 10, 5), (20, 10, 2), (20, 10, 0)],
    "천천히 나아진다":  [(20, 10, 9), (20, 10, 8), (20, 10, 7),
                       (20, 10, 6), (20, 10, 5), (20, 10, 4)],
    "제자리걸음":      [(20, 10, 3), (20, 10, 3), (20, 10, 3), (20, 10, 3)],
    "비싼 루프":       [(45, 10, 8), (45, 10, 6), (45, 10, 4)],
    "느린 루프":       [(10, 55, 8), (10, 55, 6), (10, 55, 4)],
}


def run(steps, **kw):
    g = Guards(**kw)
    for cost, secs, score in steps:
        g.record(cost, secs, score)
        if score == 0:
            return "성공", g
        why = g.check()
        if why:
            return why, g
    return "입력 소진", g


def main():
    print(f"{'상황':<14} {'끝난 이유':<10} {'회차':>4} {'쓴 비용':>7} "
          f"{'걸린 초':>7} {'마지막 점수':>10}")
    print("-" * 62)
    for name, steps in SCENARIOS.items():
        why, g = run(steps)
        last = g.scores[-1] if g.scores else "—"
        print(f"{name:<14} {why:<10} {g.rounds:>4} {g.cost:>7.0f} "
              f"{g.elapsed:>7.0f} {str(last):>10}")

    print(
        "\n네 가지가 각각 다른 걸 잡는다.\n"
        "  «천천히 나아진다» — 횟수 상한에 걸린다. 더 돌리면 될 텐데 못 돌린다\n"
        "  «제자리걸음»     — 진전 없음에 걸린다. 횟수 상한이었으면 두 번 더 헛돌았을 것\n"
        "  «비싼 루프»      — 예산 상한. 회차는 적은데 돈을 다 썼다\n"
        "  «느린 루프»      — 시간 상한. 사용자가 기다리다 떠난다\n"
        "\n하나만 두면 나머지 셋이 못 잡는 경우가 남는다.\n"
        "그리고 실무에서 제일 아픈 건 «제자리걸음»이다.\n"
        "횟수 상한만 있으면 안 될 일에 예산을 끝까지 쓰고 끝난다."
    )


if __name__ == "__main__":
    main()
