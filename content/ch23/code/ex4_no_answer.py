"""
예제 4 — 사람이 답을 안 하면 어떻게 되나.

    python3 ex4_no_answer.py

의존성 없음. 「기다리는 정책」 네 가지를 같은 상황에 적용해 본다.
"""

PENDING = [
    # (주문, 금액, 대기 시간(시간), 위험도)
    ("A-1024",   120_000,   2, "보통"),
    ("A-1031",   890_000,  26, "높음"),
    ("A-1044",   150_000,  73, "보통"),
    ("A-1050", 4_200_000, 121, "높음"),
    ("A-1066",   110_000, 200, "낮음"),
]

SLA = 24     # 시간


def p_wait(_o, _a, _h, _r):
    return "계속 기다린다", "영원히"


def p_reject(_o, _a, h, _r):
    return ("자동 거절", "안전하지만 고객이 화난다") if h > SLA else ("대기", "-")


def p_approve(_o, _a, h, _r):
    return ("자동 승인", "위험 노출") if h > SLA else ("대기", "-")


def p_escalate(_o, amount, h, risk):
    if h <= SLA:
        return "대기", "-"
    if risk == "낮음" and amount < 200_000:
        return "자동 승인", "소액·저위험만 통과"
    if h > 72:
        return "상급자 호출", "책임을 위로 올린다"
    return "담당자 재알림", "한 번 더 찌른다"


def main():
    print(f"승인 대기 {len(PENDING)}건. 약속한 응답 시간(SLA)은 {SLA}시간.\n")
    print(f"{'주문':<9}{'금액':>11}{'대기':>6}{'위험':>6}"
          f"  {'기다리기':<12}{'자동 거절':<12}{'자동 승인':<12}{'등급 올리기':<14}")
    print("-" * 92)
    for o, a, h, r in PENDING:
        row = [f"{o:<9}{a:>11,}{h:>5}h{r:>6}  "]
        for fn in (p_wait, p_reject, p_approve, p_escalate):
            act, _why = fn(o, a, h, r)
            row.append(f"{act:<12}")
        print("".join(row))

    print(
        "\n«계속 기다린다»가 기본값인 시스템이 제일 많다. 그런데 그건 정책이 아니다.\n"
        "정책을 안 정한 것이다. 200시간 묶인 건이 그 증거다.\n"
        "\n«자동 거절»은 안전해 보이지만 4,200,000원짜리를 거절한다.\n"
        "고객은 이유도 모른 채 거절 통보를 받는다.\n"
        "\n«자동 승인»은 반대로 위험을 그대로 통과시킨다.\n"
        "\n네 번째가 실무의 답에 가깝다. 시간이 지날수록 «다르게» 처리한다.\n"
        "  24시간 — 소액·저위험만 자동 통과, 나머지는 담당자 재알림\n"
        "  72시간 — 상급자를 부른다\n"
        "\n중요한 건 «무엇을 고르느냐»가 아니라 «골랐느냐»다.\n"
        "안 고르면 기본값은 언제나 «영원히 기다림»이고, 그건 아무도 원하지 않는다."
    )


if __name__ == "__main__":
    main()
