"""
예제 4 — 성형과 메시, 메시지 수를 세어 본다. 위상이 곧 비용이다.

    python3 ex4_star_vs_mesh.py

의존성 없음.
토큰 값이 궁금하면 마지막 표의 «메시지 수 × 평균 토큰» 을 보면 된다.
엣지 하나가 얼마짜리인지 아는 것, 그게 7부의 비용 모델이다.
"""

AVG_TOKENS_PER_MSG = 1_200      # 요청 + 응답 합. 팀마다 다르니 직접 재서 바꿔라.
PRICE_PER_MTOK_KRW = 4_000      # 100만 토큰당 원. 2026년 8월 기준 대략치.


def star_edges(n):
    """리더 하나가 팀원 n명과 왕복. 팀원끼리는 말하지 않는다."""
    return 2 * n


def mesh_edges(n):
    """모두가 모두와. 리더 왕복까지 포함."""
    return 2 * n + n * (n - 1)


def krw(msgs):
    return msgs * AVG_TOKENS_PER_MSG / 1_000_000 * PRICE_PER_MTOK_KRW


def main():
    print(f"{'팀원':>4} {'성형':>8} {'메시':>8} {'배수':>6} {'성형 값':>10} {'메시 값':>10}")
    print("-" * 52)
    for n in (2, 3, 5, 8, 12, 20):
        s, m = star_edges(n), mesh_edges(n)
        print(f"{n:>4} {s:>8} {m:>8} {m / s:>5.1f}x "
              f"{krw(s):>9,.0f}원 {krw(m):>9,.0f}원")

    print(
        "\n성형은 팀원 수에 비례해서 늘고, 메시는 제곱으로 는다.\n"
        "팀원 5명까지는 차이가 3배지만 20명이면 10배가 넘는다.\n"
        "\n그렇다고 성형이 늘 정답인 건 아니다. 리더가 모든 메시지를 거치니까\n"
        "리더의 컨텍스트가 먼저 찬다. 이게 리더 병목이다.\n"
        "\n판단 기준: 팀원끼리 주고받을 게 «있는지»가 아니라\n"
        "«리더를 거치면 정보가 손실되는지»로 정한다."
    )


if __name__ == "__main__":
    main()
