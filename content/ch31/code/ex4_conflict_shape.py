"""
예제 4 — 그래프에서는 충돌의 «모양»이 다르다.

    pip install kuzu
    python3 ex4_conflict_shape.py

행 하나를 고치는 것과 엣지를 고치는 것은 다르다.
엣지는 «두 노드»에 걸쳐 있어서 충돌 단위가 애매해진다.
"""

import shutil
import tempfile

import kuzu

SCENARIOS = [
    ("같은 엣지의 속성", "A: 이서연-이끔->결제팀 의 시작일 수정",
     "B: 같은 엣지의 시작일 수정", "충돌", "둘 다 같은 것을 고친다"),
    ("한 노드의 다른 엣지", "A: 이서연-이끔->결제팀 추가",
     "B: 이서연-삶->마포 추가", "충돌 아님", "겹치는 것이 없다"),
    ("단일 값 관계", "A: 이서연-이끔->결제팀 추가",
     "B: 김도현-이끔->결제팀 추가", "충돌", "팀장은 한 명 (28장)"),
    ("노드 삭제 대 엣지 추가", "A: 결제팀 노드 삭제",
     "B: 이서연-속함->결제팀 추가", "충돌", "없는 노드에 엣지를 못 단다"),
    ("양쪽에서 같은 엣지 추가", "A: 이서연-속함->결제팀 추가",
     "B: 이서연-속함->결제팀 추가", "충돌 아님", "결과가 같다 (멱등, 21장)"),
    ("서로 다른 방향", "A: 이서연-멘토->김도현 추가",
     "B: 김도현-멘토->이서연 추가", "도메인이 정함", "대칭 관계면 충돌"),
]


def build(path):
    db = kuzu.Database(path)
    c = kuzu.Connection(db)
    c.execute("CREATE NODE TABLE N(name STRING, ver INT64, PRIMARY KEY(name))")
    c.execute("CREATE REL TABLE R(FROM N TO N, kind STRING, ver INT64)")
    for n in ("이서연", "김도현", "결제팀", "마포"):
        c.execute("CREATE (:N {name:$n, ver:1})", {"n": n})
    return c


def main():
    tmp = tempfile.mkdtemp()
    build(tmp + "/db")

    print("두 에이전트가 그래프를 동시에 고치는 여섯 경우.\n")
    print(f"{'경우':<20}{'판정':<12}이유")
    print("-" * 62)
    for name, a, b, verdict, why in SCENARIOS:
        print(f"{name:<20}{verdict:<12}{why}")

    print("\n\n이제 «버전을 어디에 둘 것인가»로 같은 여섯 경우를 다시 본다.\n")
    # 노드 버전 / 엣지 버전 / 논리 단위(주어+관계종류) 로 각각 판정
    GRAN = {
        "같은 엣지의 속성":      ("막음", "막음", "막음"),
        "한 노드의 다른 엣지":   ("막음", "통과", "통과"),
        "단일 값 관계":          ("막음", "통과", "막음"),
        "노드 삭제 대 엣지 추가": ("막음", "통과", "막음"),
        "양쪽에서 같은 엣지 추가": ("막음", "막음", "막음"),
        "서로 다른 방향":        ("막음", "통과", "통과"),
    }
    WANT = {"같은 엣지의 속성": "막음", "한 노드의 다른 엣지": "통과",
            "단일 값 관계": "막음", "노드 삭제 대 엣지 추가": "막음",
            "양쪽에서 같은 엣지 추가": "통과", "서로 다른 방향": "통과"}
    print(f"{'경우':<20}{'노드 버전':<12}{'엣지 버전':<12}"
          f"{'논리 단위':<12}{'원하는 것'}")
    print("-" * 68)
    score = [0, 0, 0]
    for name, (a, b, c) in GRAN.items():
        w = WANT[name]
        for i, v in enumerate((a, b, c)):
            score[i] += v == w
        mk = lambda v: v + ("" if v == w else "*")
        print(f"{name:<20}{mk(a):<12}{mk(b):<12}{mk(c):<12}{w}")
    print(f"\n{'맞은 개수':<20}{score[0]:<12}{score[1]:<12}{score[2]:<12}"
          f"(* 는 틀린 판정)")

    print(
        "\n어느 것도 6/6 이 아니다. 그게 이 표의 요점이다.\n"
        "\n논리 단위가 5/6 로 제일 낫고, 남은 하나는 «양쪽에서 같은 엣지 추가»다.\n"
        "이건 결과가 같으니 통과시켜도 되는데 세 방식 모두 막는다.\n"
        "고치려면 버전 비교 «전에» 멱등 검사를 먼저 해야 한다.\n"
        "「쓰려는 것이 이미 있는 것과 같으면 그냥 성공으로 친다」 한 줄이면 된다.\n"
        "그러면 논리 단위가 6/6 이 된다. 21장의 멱등성이 여기서 또 쓰인다.\n"
        "\n관계형 DB 에서는 «행 하나»가 충돌 단위다. 명확하다.\n"
        "그래프에서는 그 단위가 무엇인지부터 정해야 한다.\n"
        "\n노드에 버전을 두면 «한 노드의 다른 엣지»가 헛충돌한다.\n"
        "  이서연 노드에 두 사람이 각각 다른 엣지를 다는데 버전이 부딪힌다.\n"
        "  실제로는 안 겹치는데 막힌다. 이걸 «가짜 충돌»이라고 한다.\n"
        "\n엣지에 버전을 두면 «단일 값 관계»를 못 잡는다.\n"
        "  이서연-이끔->결제팀 과 김도현-이끔->결제팀 은 다른 엣지다.\n"
        "  각자 버전이 따로라 둘 다 통과한다. 그러면 팀장이 둘이 된다.\n"
        "\n그래서 실무에서는 «논리적 충돌 단위»를 따로 정한다.\n"
        "  단일 값 관계 → 「주어 + 관계 종류」를 한 단위로 본다\n"
        "  다중 값 관계 → 엣지 하나가 한 단위\n"
        "  노드 삭제   → 그 노드에 걸린 모든 엣지와 충돌\n"
        "\n이 표를 코드로 갖고 있어야 한다. 28장의 SINGLE_VALUED 목록이\n"
        "여기서 다시 쓰인다. 같은 목록이 두 문제를 푼다."
    )
    shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
