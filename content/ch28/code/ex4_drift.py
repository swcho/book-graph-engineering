"""
예제 4 — 그래프가 스스로 자라면 «어디로» 자라나.

    python3 ex4_drift.py

의존성 없음. 에이전트가 자기가 쓴 것을 다시 읽고 또 쓰는 루프를
100세대 돌려서 분포가 어떻게 변하는지 본다.
"""

import random

KINDS = ["관계", "선호", "제약", "사건"]
START = {"관계": 40, "선호": 30, "제약": 20, "사건": 10}

# 에이전트가 «어떤 종류를 읽으면 어떤 종류를 새로 쓰는가»
# 관계를 읽으면 관계를 더 쓴다. 이게 편향의 원인이다.
EMIT = {
    "관계": {"관계": 0.62, "선호": 0.18, "제약": 0.05, "사건": 0.15},
    "선호": {"관계": 0.20, "선호": 0.55, "제약": 0.10, "사건": 0.15},
    "제약": {"관계": 0.25, "선호": 0.20, "제약": 0.35, "사건": 0.20},
    "사건": {"관계": 0.40, "선호": 0.20, "제약": 0.05, "사건": 0.35},
}
GEN = 100
PER_GEN = 20


def step(counts, rng, human_share=0.0):
    total = sum(counts.values())
    new = dict(counts)
    for _ in range(PER_GEN):
        if rng.random() < human_share:
            # 사람이 넣는 사실은 원래 분포를 따른다
            k = rng.choices(KINDS, [START[x] for x in KINDS])[0]
            new[k] += 1
            continue
        # 에이전트가 기존 그래프에서 하나를 읽고, 그것에 이끌려 새 사실을 쓴다
        seed = rng.choices(KINDS, [counts[x] for x in KINDS])[0]
        emit = EMIT[seed]
        k = rng.choices(KINDS, [emit[x] for x in KINDS])[0]
        new[k] += 1
    return new


def run(human_share, seed=3):
    rng = random.Random(seed)
    c = dict(START)
    snaps = {}
    for g in range(1, GEN + 1):
        c = step(c, rng, human_share)
        if g in (1, 10, 50, 100):
            t = sum(c.values())
            snaps[g] = {k: c[k] / t for k in KINDS}
    return snaps


def show(title, snaps):
    print(f"\n[{title}]")
    print(f"{'세대':>5}" + "".join(f"{k:>9}" for k in KINDS))
    print("-" * 41)
    print(f"{0:>5}" + "".join(f"{START[k] / 100:>8.0%}" for k in KINDS))
    for g, d in snaps.items():
        print(f"{g:>5}" + "".join(f"{d[k]:>8.0%}" for k in KINDS))


def main():
    print("에이전트가 자기가 쓴 그래프를 읽고 또 쓴다. 100세대.")
    print("시작 분포: 관계 40%, 선호 30%, 제약 20%, 사건 10%")

    show("사람 개입 0% — 에이전트만 쓴다", run(0.0))
    show("사람 개입 20%", run(0.2))

    print(
        "\n«제약»이 20%에서 9%로 반토막 났다. 그리고 «사건»이 10%에서 19%로 두 배가 됐다.\n"
        "«관계»는 40%에서 42%로 거의 안 변했다. 제가 예상한 것과 다르다.\n"
        "\n왜 이렇게 되나. 에이전트는 그래프에서 읽은 것에 이끌려 쓴다.\n"
        "그래서 «자기를 잘 낳는 종류»가 살아남는다.\n"
        "  관계 → 관계 62%    제약 → 제약 35%    사건 → 사건 35%\n"
        "\n제약은 자기 재생산율이 낮다. 그런데 사건도 35%로 같은데 왜 사건은 늘었나.\n"
        "«남이 나를 낳아 주는» 비율이 다르기 때문이다.\n"
        "관계를 읽으면 사건을 쓸 확률이 15%, 제약은 5%다. 세 배 차이다.\n"
        "그리고 관계가 제일 많으니 그 세 배가 계속 벌어진다.\n"
        "\n정리하면 살아남는 종류를 정하는 건 «자기 재생산율»만이 아니라\n"
        "«전체 분포와의 곱»이다. 제일 흔한 종류가 무엇을 낳느냐가 지배한다.\n"
        "\n이게 그래프 드리프트다. 아무도 «관계를 늘려라»라고 안 했는데\n"
        "루프를 돌리면 저절로 그렇게 된다. 구조가 그렇게 생겼기 때문이다.\n"
        "\n무서운 건 «제약»이 줄어드는 방향이라는 점이다.\n"
        "27장에서 봤듯 제약은 잃으면 제일 아픈 종류다.\n"
        "그리고 여기서는 지워서 사라지는 게 아니라 «비율이 묽어져서» 사라진다.\n"
        "조회할 때 상위 k 개를 뽑으면 제약이 안 뽑히기 시작한다.\n"
        "\n사람 개입 20%를 넣으면 제약이 9%가 아니라 12%에서 멈춘다.\n"
        "감속은 되는데 방향은 그대로다. «가끔 사람이 확인한다»로는 못 막는다.\n"
        "5분의 1을 사람이 넣어도 이 정도다. 개입을 절반으로 올리는 건 현실적이지 않다.\n"
        "\n대응은 종류별 «비율 상한»을 두는 것이다.\n"
        "  - 관계가 전체의 55%를 넘으면 관계 쓰기를 멈춘다\n"
        "  - 제약이 10% 아래로 내려가면 경보를 울린다\n"
        "\n비율은 매일 재면 된다. 쿼리 한 줄이다.\n"
        "그리고 이 지표가 없으면 «묽어지는» 것을 영영 못 본다."
    )


if __name__ == "__main__":
    main()
