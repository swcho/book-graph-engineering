"""
예제 5 — 스스로 넓히는 루프에 «어디까지»를 정한다.

    python3 ex5_expansion_budget.py

의존성 없음. 넓히기 정책 네 가지를 놓고
「새로 얻은 사실」과 「들인 값」과 「틀린 사실」을 같이 센다.
"""

import random

# 노드 한 개를 넓힐 때: 새 사실 몇 개, 그중 맞는 비율, 드는 값
YIELD_BY_HOP = {1: (3.2, 0.86), 2: (2.1, 0.71), 3: (1.4, 0.52), 4: (0.9, 0.38)}
COST_PER_EXPAND = 1_400          # 토큰
SEED_NODES = 12


def expand(policy, rng):
    """정책에 따라 넓히고 (새 사실, 맞는 것, 틀린 것, 토큰) 을 돌려준다."""
    frontier = SEED_NODES
    got = right = wrong = tok = 0
    for hop in range(1, 5):
        if not policy(hop, got, wrong, tok):
            break
        y, acc = YIELD_BY_HOP[hop]
        new = frontier * y
        tok += frontier * COST_PER_EXPAND
        r = new * acc
        got += new
        right += r
        wrong += new - r
        frontier = int(r)          # 맞는 것만 다음 홉의 씨앗이 된다
    return got, right, wrong, tok


POLICIES = {
    "끝까지 (4홉)":        lambda h, g, w, t: True,
    "2홉까지":             lambda h, g, w, t: h <= 2,
    "토큰 예산 60,000":    lambda h, g, w, t: t < 60_000,
    "틀린 것 30개 넘으면 중단": lambda h, g, w, t: w < 30,
}


def main():
    rng = random.Random(5)
    print(f"씨앗 노드 {SEED_NODES}개에서 넓힌다. 홉이 깊어질수록 정확도가 떨어진다.\n")
    print(f"{'홉':>3}{'노드당 새 사실':>14}{'맞을 확률':>10}")
    print("-" * 30)
    for h, (y, a) in YIELD_BY_HOP.items():
        print(f"{h:>3}{y:>14.1f}{a:>10.0%}")

    print(f"\n{'정책':<24}{'새 사실':>9}{'맞는 것':>9}{'틀린 것':>9}"
          f"{'토큰':>10}{'맞는 것/1만토큰':>16}")
    print("-" * 80)
    for name, pol in POLICIES.items():
        g, r, w, t = expand(pol, rng)
        eff = r / (t / 10_000) if t else 0
        print(f"{name:<24}{g:>9.0f}{r:>9.0f}{w:>9.0f}{t:>10,.0f}{eff:>16.1f}")

    print(
        "\n«끝까지»가 새 사실을 제일 많이 얻는다. 그리고 틀린 것도 제일 많다.\n"
        "\n효율 칸(맞는 것 / 1만 토큰)을 보시라. 얕게 멈추는 쪽이 효율이 높다.\n"
        "깊은 홉은 값은 그대로 드는데 수확이 적고 정확도도 낮기 때문이다.\n"
        "\n그런데 «효율이 높다»가 «좋다»는 아니다.\n"
        "2홉에서 멈추면 3~4홉에서만 나오는 사실을 영영 못 얻는다.\n"
        "그리고 그런 사실이 대개 «사람이 몰랐던 것»이라 값어치가 크다.\n"
        "\n그래서 저는 두 가지를 같이 쓴다.\n"
        "  - 평소에는 2홉. 싸고 정확하다\n"
        "  - 주기적으로(주 1회) 4홉까지 넓히되 «사람 검토 대기»로 넣는다\n"
        "\n깊은 홉의 결과를 그래프에 바로 안 쓰는 게 요점이다.\n"
        "정확도 38%짜리를 바로 쓰면 예제 1의 상황이 된다.\n"
        "\n표에서 하나 이상한 게 보인다. «토큰 예산 60,000»이 63,000 토큰을 썼다.\n"
        "예산을 넘겼다. 홉을 «시작하기 전»에만 검사하고 중간에는 안 봐서다.\n"
        "2홉을 시작할 때 누적이 16,800이라 통과했고, 그 홉이 46,200을 더 썼다.\n"
        "\n이게 실무에서 자주 나는 버그다. 예산을 «단위 작업 앞»에서만 보면\n"
        "단위 작업 하나가 예산 전체보다 클 때 못 막는다.\n"
        "고치려면 홉 안에서 노드 단위로 검사하거나, 홉의 예상 값을 미리 재야 한다.\n"
        "\n그리고 «틀린 것 30개 넘으면 중단»을 눈여겨보시라.\n"
        "홉 수가 아니라 «품질»로 멈추는 정책이다. 20장의 «진전 없음»과 같은 발상이다.\n"
        "다만 이것도 30개를 «넘고 나서» 안다. 틀린 사실 30개가 이미 들어간 뒤다.\n"
        "그래서 이 정책은 «쓰기 전 대기열»과 같이 써야 한다.\n"
        "일단 대기열에 쌓고, 중단 조건에 걸리면 대기열을 통째로 버린다."
    )


if __name__ == "__main__":
    main()
