"""
예제 4 — 신뢰도를 어디서 얻을까. 모델이 말하는 확신은 믿을 게 못 된다.

    python3 ex4_confidence.py

의존성 없음.
"""

import random
from collections import defaultdict

random.seed(20260801)

# 같은 문서를 세 번 돌린 결과. 모델은 매번 조금씩 다르게 답한다.
RUNS = [
    {("가온테크", "체결", "C-2025-118"), ("C-2025-118", "담당", "김하늘"),
     ("가온테크", "업종", "IT 서비스"), ("C-2025-118", "상대", "나루소프트")},
    {("가온테크", "체결", "C-2025-118"), ("C-2025-118", "담당", "김하늘"),
     ("C-2025-118", "상대", "나루소프트"), ("C-2025-118", "체결일", "2025-06-02")},
    {("가온테크", "체결", "C-2025-118"), ("C-2025-118", "담당", "김하늘 부장"),
     ("C-2025-118", "상대", "나루소프트"), ("가온테크", "규모", "중견기업")},
]

# 모델이 스스로 매긴 확신도 (자기 보고)
SELF_REPORTED = {
    ("가온테크", "체결", "C-2025-118"): 0.95,
    ("C-2025-118", "담당", "김하늘"): 0.92,
    ("C-2025-118", "상대", "나루소프트"): 0.90,
    ("C-2025-118", "체결일", "2025-06-02"): 0.88,
    ("가온테크", "업종", "IT 서비스"): 0.91,     # 지어낸 건데 확신이 높다
    ("가온테크", "규모", "중견기업"): 0.87,       # 이것도
    ("C-2025-118", "담당", "김하늘 부장"): 0.85,
}

TRUE = {("가온테크", "체결", "C-2025-118"), ("C-2025-118", "담당", "김하늘"),
        ("C-2025-118", "상대", "나루소프트"), ("C-2025-118", "체결일", "2025-06-02")}


def main():
    votes = defaultdict(int)
    for run in RUNS:
        for t in run:
            votes[t] += 1

    print(f"{'트리플':<44} {'자기보고':>8} {'표 수':>6} {'실제'}")
    print("-" * 74)
    for t in sorted(votes, key=lambda x: (-votes[x], -SELF_REPORTED.get(x, 0))):
        label = " 참" if t in TRUE else " 거짓"
        print(f"{str(t):<44} {SELF_REPORTED.get(t, 0):>8.2f} "
              f"{votes[t]:>4}/3 {label}")

    print("\n두 신호를 임계로 갈라 보면")
    for name, key, th in (("자기 보고 0.90 이상", lambda t: SELF_REPORTED.get(t, 0), 0.90),
                          ("3번 중 3번 나옴", lambda t: votes[t] / 3, 0.99)):
        picked = {t for t in votes if key(t) >= th}
        tp = len(picked & TRUE)
        prec = tp / len(picked) if picked else 0
        rec = tp / len(TRUE)
        print(f"  {name:<20} 정밀도 {prec:.3f}  재현율 {rec:.3f}  "
              f"(뽑은 것 {len(picked)}개)")

    print(
        "\n«3번 중 3번»은 정밀도 1.000 인데 재현율이 0.500 이다.\n"
        "맞는 트리플 둘(체결일, 그리고 표기가 갈린 담당)을 놓쳤다.\n"
        "즉 표 세기는 «확실한 것만 고르는» 쪽으로 치우친다.\n"
        "\n자기 보고는 거짓에도 0.91, 0.87 을 준다. 참과 구분이 안 된다.\n"
        "여러 번 돌려 «몇 번 나왔나»를 세는 쪽이 훨씬 잘 갈라낸다.\n"
        "지어낸 것은 매번 다르게 지어내기 때문이다.\n"
        "\n대가는 값이다. 세 번 돌리면 값도 세 배다.\n"
        "\n제 절충안은 이렇다.\n"
        "  1차 — 한 번만 돌리고 근거 검사로 거른다 (싸다)\n"
        "  2차 — 근거 검사를 통과했지만 어휘 밖이거나 새 노드를 만드는 것만\n"
        "        두 번 더 돌려 표를 센다 (비싼 검사를 소수에만)\n"
        "\n«김하늘»과 «김하늘 부장»이 갈린 것도 눈에 띈다.\n"
        "표 수로는 2:1 인데, 이건 14장의 엔티티 해상도로 넘어갈 문제다.\n"
        "추출 단계에서 풀려고 하면 안 된다. 단계마다 할 일이 있다."
    )


if __name__ == "__main__":
    main()
