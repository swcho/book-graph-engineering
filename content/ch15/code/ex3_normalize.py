"""
예제 3 — 어휘 정규화. «뜻은 맞는데 이름이 다른» 트리플을 살려 낸다.

    python3 ex3_normalize.py

의존성 없음.
"""

from docs import GOLD, VOCAB_PREDICATES

# 모델이 실제로 내놓은 술어들 (여러 번 돌리면 이보다 훨씬 다양하다)
OBSERVED = ["체결", "계약체결일자", "체결일자", "계약일", "담당", "담당자",
            "책임자", "해지", "계약해지", "해지사유", "사유", "협업", "업종"]

# 사람이 만든 매핑 표. 이게 자산이다.
SYNONYM = {
    "계약체결일자": "체결일", "체결일자": "체결일", "계약일": "체결일",
    "담당자": "담당", "책임자": "담당",
    "계약해지": "해지", "사유": "해지사유",
}


def normalize(pred):
    p = SYNONYM.get(pred, pred)
    return p if p in VOCAB_PREDICATES else None


def main():
    print(f"{'모델이 낸 술어':<14} {'매핑 결과':<10} 판정")
    print("-" * 46)
    ok = unmapped = 0
    for p in OBSERVED:
        n = normalize(p)
        if n:
            ok += 1
            mark = "그대로" if n == p else f"→ {n}"
            print(f"{p:<14} {n:<10} {mark}")
        else:
            unmapped += 1
            print(f"{p:<14} {'—':<10} 어휘 밖 — 보류함에")

    print(f"\n매핑됨 {ok}개, 보류 {unmapped}개")

    print(
        "\n보류함이 이 파이프라인의 심장이다.\n"
        "«협업»과 «업종»이 여기 쌓인다. 그리고 주에 한 번 사람이 본다.\n"
        "\n볼 때 셋 중 하나를 정한다.\n"
        "  1. 어휘에 추가한다 — 실제로 필요한 관계였다\n"
        "  2. 동의어로 매핑한다 — 있는 술어와 같은 뜻이었다\n"
        "  3. 버린다 — 우리가 안 다루는 것이다\n"
        "\n이 결정을 SYNONYM 표에 쌓으면 다음부터 자동으로 처리된다.\n"
        "제 경우 3개월쯤 쌓으니 보류율이 18%에서 3%로 떨어졌다.\n"
        "\n중요한 건 «보류»가 «버림»과 다르다는 것이다.\n"
        "버리면 그 정보가 사라지고, 보류하면 나중에 살릴 수 있다.\n"
        "그리고 보류함 크기가 곧 «우리 어휘가 현실과 얼마나 어긋나는가»의 지표다."
    )


if __name__ == "__main__":
    main()
