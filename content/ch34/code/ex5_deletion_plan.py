"""
예제 5 — 삭제 요청 하나를 «검사 가능한 절차»로 만든다.

    python3 ex5_deletion_plan.py

의존성 없음. 노드 종류마다 처리 방침을 표로 두고,
요청 하나를 그 표에 통과시킨다.
"""

# 노드 종류별 방침
POLICY = {
    "Person":   ("삭제",   "개인 그 자체"),
    "Contact":  ("삭제",   "연락처"),
    "Msg":      ("본문 마스킹", "발화 — 이름·연락처만 가린다"),
    "Doc":      ("작성자 익명화", "산출물은 회사 자산"),
    "Team":     ("유지",   "개인정보 아님"),
    "Stat":     ("재계산", "집계는 남기되 다시 센다"),
    "Fact":     ("유지",   "개인을 안 가리키면"),
    "Answer":   ("유지",   "회사의 결정 기록"),
    "Run":      ("행위자 익명화", "누가 돌렸는지만 가린다"),
    "Event":    ("식별자 치환", "30장 — 이벤트는 못 지운다"),
}

# 이번 요청에서 걸린 것들
HIT = [
    ("p1", "Person", "김도현"),
    ("c1", "Contact", "kim@example.org"),
    ("m1", "Msg", "김도현: 마포에서 봐요"),
    ("d1", "Doc", "3분기 보고서"),
    ("t1", "Team", "결제팀"),
    ("s1", "Stat", "팀별 문서 수"),
    ("f1", "Fact", "결제팀은 문서 생산이 많다"),
    ("a1", "Answer", "결제팀에 리소스를 더 배정"),
    ("r1", "Run", "분기 분석 #901"),
    ("e1", "Event", "p1 을 결제팀에 추가"),
    ("x1", "Photo", "회식 사진"),          # 방침이 없다
]


def main():
    print("삭제 요청 하나. 영향 범위에 걸린 노드를 방침 표에 통과시킨다.\n")
    print(f"{'노드':<6}{'종류':<10}{'라벨':<26}{'방침':<14}이유")
    print("-" * 82)
    unknown = []
    counts = {}
    for i, kind, label in HIT:
        if kind not in POLICY:
            unknown.append((i, kind, label))
            print(f"{i:<6}{kind:<10}{label:<26}{'??':<14}"
                  f"방침 없음 — 사람이 정해야 한다")
            continue
        act, why = POLICY[kind]
        counts[act] = counts.get(act, 0) + 1
        print(f"{i:<6}{kind:<10}{label:<26}{act:<14}{why}")

    print(f"\n처리 요약: {counts}")
    if unknown:
        print(f"막힘: 방침 없는 종류 {len(unknown)}개 — "
              f"{[u[1] for u in unknown]}")

    print(
        "\nPhoto 에서 막혔다. 방침 표에 없는 종류다.\n"
        "\n이게 이 표의 값어치다. «모르는 것을 모른다고» 말해 준다.\n"
        "방침이 없으면 자동으로 처리하지 않고 멈춘다.\n"
        "\n표가 없으면 어떻게 되나. 담당자가 그때그때 판단한다.\n"
        "그리고 다음 요청이 오면 다른 담당자가 다르게 판단한다.\n"
        "「지난번엔 지웠는데 이번엔 안 지웠다」가 되면 그게 더 큰 문제다.\n"
        "\n방침을 정할 때 물어야 할 것은 하나다.\n"
        "  «이 노드가 개인을 가리키는가, 아니면 개인이 만든 것인가?»\n"
        "  가리키면 지우고, 만든 것이면 «만든 사람만» 지운다.\n"
        "\n그리고 Event 를 보시라. «식별자 치환»이다. 지우는 게 아니다.\n"
        "30장에서 이벤트 로그는 추가 전용이라 못 지운다고 했다.\n"
        "그래서 이벤트에 개인정보를 «직접 안 넣는» 설계가 여기서 값을 한다.\n"
        "식별자만 들어 있으면 그 식별자를 가리키는 표에서만 지우면 된다.\n"
        "\n마지막으로, 이 절차는 «며칠 걸린다».\n"
        "재계산이 있고 백업이 있고 사람 확인이 있다.\n"
        "그래서 「30일 안에 처리」 같은 약속을 하려면 이 절차의 실제 소요를 재 둬야 한다."
    )


if __name__ == "__main__":
    main()
