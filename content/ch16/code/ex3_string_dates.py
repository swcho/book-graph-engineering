"""
예제 3 — 3장에서 예고한 그것. 날짜를 문자열로 비교하면 언제 배신하나.

    python3 ex3_string_dates.py

의존성 없음.
"""

from datetime import date

CASES = [
    # (설명, 값 두 개, 문자열 비교, 날짜 비교)
    ("자릿수가 맞을 때",        "2024-03-11", "2025-06-02"),
    ("월에 0이 빠졌을 때",      "2024-3-11",  "2024-12-01"),
    ("연-월만 있을 때",         "2024-08",    "2024-8"),
    ("슬래시 표기가 섞였을 때",   "2024/03/11", "2024-06-02"),
    ("연도만 있을 때",          "2024",       "2024-01-01"),
    ("시각이 붙었을 때",        "2024-03-11", "2024-03-11T09:00"),
]


def parse(s):
    """실무에서 흔히 쓰는 관대한 파서. 이 관대함이 사고를 만든다."""
    s = s.replace("/", "-").split("T")[0]
    parts = [int(x) for x in s.split("-")]
    while len(parts) < 3:
        parts.append(1)
    return date(*parts)


def main():
    print(f"{'상황':<20} {'A':<14} {'B':<20} {'문자열':>8} {'날짜':>6} {'같나'}")
    print("-" * 78)
    mismatch = 0
    for label, a, b in CASES:
        s_cmp = "A<B" if a < b else ("A=B" if a == b else "A>B")
        pa, pb = parse(a), parse(b)
        d_cmp = "A<B" if pa < pb else ("A=B" if pa == pb else "A>B")
        same = s_cmp == d_cmp
        mismatch += 0 if same else 1
        print(f"{label:<20} {a:<14} {b:<20} {s_cmp:>8} {d_cmp:>6} "
              f"{'예' if same else '아니오 ←'}")

    print(f"\n6건 중 {mismatch}건에서 문자열 비교가 틀린 답을 낸다.")

    print(
        "\n무서운 건 «틀리는 방식»이다.\n"
        "예외가 안 난다. 그냥 조용히 반대로 정렬된다.\n"
        "\n«2024-3-11» 과 «2024-12-01» 을 문자열로 비교하면 3월이 12월보다 크다.\n"
        "«3» 이 «1» 보다 크니까. 유효 기간 자르기가 여기서 무너진다.\n"
        "\n제가 겪은 건 이랬다. 외부 시스템에서 들어온 날짜 일부가 «2024-3-11» 형식이었고,\n"
        "그 레코드들만 계약 만료 계산이 틀렸다. 전체의 4%였다.\n"
        "월별 집계는 멀쩡했다. 4% 는 오차 범위처럼 보였으니까.\n"
        "발견한 건 고객이 «우리 계약 왜 만료됐냐»고 전화했을 때였다.\n"
        "\n예방법 두 가지.\n"
        "  1. 적재 시점에 날짜 타입으로 파싱한다. 문자열로 두지 않는다.\n"
        "  2. 파싱 실패는 «조용히 넘기지» 말고 차단 등급 위반으로 올린다 (13장).\n"
        "\n2번을 안 하면 1번이 무력해진다. 파싱 못 한 걸 원본 문자열로 두게 되니까."
    )


if __name__ == "__main__":
    main()
