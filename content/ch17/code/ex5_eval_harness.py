from collections import defaultdict

# (질문 유형, 방식, 정답률)
RESULTS = [
    ("사실조회", "벡터만", 0.91), ("사실조회", "그래프 붙임", 0.89),
    ("단일요약", "벡터만", 0.88), ("단일요약", "그래프 붙임", 0.85),
    ("다중홉",  "벡터만", 0.47), ("다중홉",  "그래프 붙임", 0.78),
    ("비교",    "벡터만", 0.39), ("비교",    "그래프 붙임", 0.74),
    ("전역집계", "벡터만", 0.18), ("전역집계", "그래프 붙임", 0.71),
]

# 실제 질문 분포 두 가지
MIXES = {
    "A 조직 (사실 조회 위주)": {"사실조회": 0.62, "단일요약": 0.24,
                              "다중홉": 0.09, "비교": 0.03, "전역집계": 0.02},
    "B 조직 (분석 위주)":     {"사실조회": 0.22, "단일요약": 0.13,
                              "다중홉": 0.28, "비교": 0.19, "전역집계": 0.18},
}


def weighted(mix, method):
    acc = {k: v for k, m, v in RESULTS if m == method}
    return sum(mix[k] * acc[k] for k in mix)


def main():
    print(f"{'질문 유형':<10} {'벡터만':>8} {'그래프 붙임':>12} {'차이':>8}")
    print("-" * 42)
    for kind in ("사실조회", "단일요약", "다중홉", "비교", "전역집계"):
        v = next(x for k, m, x in RESULTS if k == kind and m == "벡터만")
        g = next(x for k, m, x in RESULTS if k == kind and m == "그래프 붙임")
        mark = " ←" if g < v else ""
        print(f"{kind:<10} {v:>8.2f} {g:>12.2f} {g-v:>+8.2f}{mark}")

    print(f"\n{'조직':<24} {'벡터만':>8} {'그래프 붙임':>12} {'판정'}")
    print("-" * 60)
    for name, mix in MIXES.items():
        v, g = weighted(mix, "벡터만"), weighted(mix, "그래프 붙임")
        verdict = "붙일 값 있음" if g - v > 0.03 else "붙이지 마라"
        print(f"{name:<24} {v:>8.3f} {g:>12.3f}  {verdict}")

    print(
        "\n같은 표, 다른 결론이다. 질문 분포가 다르기 때문이다.\n"
        "\nA 조직은 +0.029 다. 오차 범위이고, 붙이는 값(복잡도·지연·갱신 비용)을\n"
        "생각하면 안 붙이는 게 맞다. 유형별로는 사실조회가 0.02 «나빠졌고».\n"
        "B 조직은 +0.240 이다. 명확하다.\n"
        "\n그래서 «GraphRAG 가 좋다더라»는 질문이 잘못됐다.\n"
        "«우리 질문 분포에서 좋은가»가 맞는 질문이다.\n"
        "\n그리고 이 표를 만드는 데 필요한 건 질문 로그 100건이다.\n"
        "유형별로 나누고 각 방식을 돌려 보면 반나절이면 나온다.\n"
        "그 반나절이 몇 달짜리 도입 결정을 정한다."
    )


if __name__ == "__main__":
    main()
