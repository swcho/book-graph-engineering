# - 네 곡선 모두 **초반이 평평합니다.** $s=2$ 정도로는 비중이 거의 안 움직입니다.
#   "모델이 두 배 빨라졌다"는 뉴스만으로는 주장 1이 흔들리지 않습니다.
# - 60% 점선을 지나는 $x$좌표가 각 $p$의 임계 가속입니다. $p$가 커질수록
#   그 점이 오른쪽으로 **급격히** 밀립니다(2.7 → 6 → 12.2 → 66).
# - $s=10$ 세로선에서 $p=0.9$ 곡선은 선 아래(반증), $p=0.948$ 곡선은 선 위(유지).
#   **같은 10배인데 판정이 갈립니다.** 그래서 반증 조건은 "10배"만으로 완성되지 않고
#   "분기마다 구간별 시간을 다시 재라"가 반드시 붙어야 합니다.

# %% [markdown]
# ## 정리
#
# | 물어볼 것 | 답 |
