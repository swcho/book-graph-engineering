# %% [markdown]
# # 주장 1의 반증 조건 — 모델만 10배 빨라지면 비중은 얼마가 되나
#
# 35장의 주장 1은 이렇습니다.
#
# > **모델 호출이 응답 시간의 90% 넘게 차지한다** (33장, 확신 35%)
#
# 반증 조건은 이렇습니다.
#
# > **같은 작업의 모델 지연이 10분의 1이 되면 모델 호출 비중이 60% 아래로 내려간다.**
# > 분기마다 구간별 시간을 다시 재야 한다.
#
# 여기서 쓰는 산수는 **암달의 법칙**(Amdahl's law)과 똑같습니다.
# 전체 지연을 1로 정규화하고, 그 중 비율 $p$가 모델 호출, 나머지 $1-p$가
# 모델이 아닌 구간(조회·직렬화·네트워크·정책 검사 등)이라고 둡니다.
#
# 모델 구간만 $s$배 빨라지면
#
# $$T' = \frac{p}{s} + (1-p), \qquad p' = \frac{p/s}{\;p/s + (1-p)\;}$$
#
# 핵심은 **분모가 같이 줄어든다**는 것입니다. 그래서 비중은 $p/s$로 떨어지지 않고
# 위 식처럼 훨씬 완만하게 떨어집니다.

# %%
def _show(fig):
    try:
        from IPython import get_ipython
        if get_ipython() is not None:  # VSCode 셀/Jupyter에서만 렌더링
            fig.show()
    except ImportError:
        pass


def new_share(p: float, s: float) -> float:
    """초기 모델 비중 p, 모델 구간 가속 s배 → 새 모델 비중 p'."""
    model = p / s
    rest = 1.0 - p
    return model / (model + rest)


def total_speedup(p: float, s: float) -> float:
    """암달의 법칙: 전체 지연이 몇 배 짧아지는가."""
    return 1.0 / (p / s + (1.0 - p))


print(f"{new_share(0.9, 10):.4f}")     # 출력: 0.4737
print(f"{total_speedup(0.9, 10):.4f}")  # 출력: 5.2632

# %% [markdown]
# ## 1단계 — $p=0.9$, $s=10$ 을 손으로 따라가기
#
# $$\frac{p}{s} = \frac{0.9}{10} = 0.09, \qquad 1-p = 0.1$$
#
# $$p' = \frac{0.09}{0.09 + 0.1} = \frac{0.09}{0.19} = 0.4737$$
#
# 모델 비중이 **90% → 47.4%**. 반증선 60%를 확실히 밑돕니다.
# 그런데 전체 지연은 $1/0.19 = 5.26$배밖에 안 짧아집니다.
# 모델을 10배 빠르게 만들어도 전체는 5.3배. 남은 10%가 발목을 잡습니다.

# %%
p, s = 0.9, 10.0
model_before, rest = p, 1 - p
model_after = p / s
total_after = model_after + rest

print(f"이전   모델 {model_before:.3f} + 기타 {rest:.3f} = {model_before + rest:.3f}  (모델 비중 {p:>6.1%})")
print(f"이후   모델 {model_after:.3f} + 기타 {rest:.3f} = {total_after:.3f}  (모델 비중 {new_share(p, s):>6.1%})")
print(f"전체 단축 {total_speedup(p, s):.2f}배 (모델만 보면 {s:.0f}배)")
print(f"반증 판정: p'={new_share(p, s):.1%} < 60% → 주장 1은 반증된다")
# 출력: 이전   모델 0.900 + 기타 0.100 = 1.000  (모델 비중  90.0%)
# 출력: 이후   모델 0.090 + 기타 0.100 = 0.190  (모델 비중  47.4%)
# 출력: 전체 단축 5.26배 (모델만 보면 10배)
# 출력: 반증 판정: p'=47.4% < 60% → 주장 1은 반증된다

# %% [markdown]
# ## 2단계 — 임계 가속 $s^\*$ 역산: 몇 배 빨라지면 60%를 깨나
#
# $p' = q$ 가 되는 $s$를 풀면
#
# $$\frac{p/s}{p/s + (1-p)} = q \;\Longrightarrow\; s^{*} = \frac{p\,(1-q)}{q\,(1-p)}$$
#
# $q = 0.6$ 을 넣으면 $s^{*} = \dfrac{2p}{3(1-p)}$ 라는 아주 짧은 식이 됩니다.
#
# - $p = 0.90$ → $s^{*} = \dfrac{1.8}{0.3} = \mathbf{6.0}$
# - $p = 0.948$ (33장의 실측값) → $s^{*} = \dfrac{1.896}{0.156} = \mathbf{12.2}$
#
# 즉 반증 조건이 요구하는 10배는 $p=0.9$ 기준으로는 **여유 있게 넘고**,
# 33장 실측 94.8% 기준으로는 **아직 못 넘습니다**. 그래서 10배는
# "확실히 깨지는 쪽"이 아니라 "깨지는지 아닌지가 갈리는 자리"에 놓인 숫자입니다.

# %%
def critical_speedup(p: float, q: float = 0.6) -> float:
    """비중이 q로 떨어지게 하는 가속 배수 s*."""
    return p * (1 - q) / (q * (1 - p))


for p0 in (0.80, 0.90, 0.948, 0.99):
    s_star = critical_speedup(p0, 0.6)
    print(f"p={p0:<6.3f}  s*={s_star:>6.2f}배   s=10일 때 p'={new_share(p0, 10):>6.1%}"
          f"   전체 {total_speedup(p0, 10):.2f}배")
# 출력: p=0.800   s*=  2.67배   s=10일 때 p'= 28.6%   전체 3.57배
# 출력: p=0.900   s*=  6.00배   s=10일 때 p'= 47.4%   전체 5.26배
# 출력: p=0.948   s*= 12.15배   s=10일 때 p'= 64.6%   전체 6.81배
# 출력: p=0.990   s*= 66.00배   s=10일 때 p'= 90.8%   전체 9.17배

# %% [markdown]
# 위 표가 반증 조건의 성질을 다 말해 줍니다.
#
# - $p$가 0.9에서 0.948로 **5%p만 올라가도** 임계 가속은 6배 → 12.2배로 **두 배**가 됩니다.
#   비중은 $1-p$(모델 아닌 구간)의 역수에 민감해서, 90%와 95%는 전혀 다른 세계입니다.
# - $p=0.99$ 라면 60%를 깨는 데 **66배**가 필요합니다. 10배로는 90.8%, 거의 안 움직입니다.
# - 그래서 "몇 배 빨라졌나"만 보고 판정하면 안 되고, **지금의 $p$를 먼저 재야** 합니다.

# %% [markdown]
# ## 3단계 — 왜 하필 60%인가
#
# 60%가 특별한 물리량은 아닙니다. 다만 **판정선으로 쓸 만한** 성질이 셋 있습니다.
#
# 1. **여전히 지배 구간이지만 "압도적"은 아닌 자리.** 90%는 "모델만 보면 된다"이고,
#    50% 아래는 "모델 말고도 봐야 한다"입니다. 60%는 그 사이 경계에 있어서
#    33장의 실무 결론("최적화는 모델 호출부터")이 **성립하는 마지막 지점**입니다.
# 2. **측정 잡음보다 크게 벌어진 간격.** 90%에서 60%는 30%p 차이입니다.
#    구간별 시간 측정의 분기 간 흔들림(보통 몇 %p)에 묻히지 않아서,
#    "잡음인가 추세인가"를 따질 필요가 없습니다.
# 3. **한쪽으로만 넘는 선.** $p'$는 $s$에 대해 단조 감소합니다.
#    한 번 60% 아래로 내려가면 모델이 더 느려지지 않는 한 되돌아오지 않습니다.
#    되돌아오지 않는 선이라야 "이 값이 이렇게 되면 틀린다"가 성립합니다.
#
# 반대로 90%를 그대로 반증선으로 쓰면 안 됩니다. 실측이 94.8%인데 판정선이 90%면
# 아주 작은 개선(위 표에서 $s^{*}=1.85$배)에도 "틀렸다"가 나옵니다. 그건 너무 예민합니다.

# %%
# 90%를 반증선으로 쓰면 얼마나 예민해지는가
for q in (0.90, 0.80, 0.70, 0.60, 0.50):
    print(f"반증선 {q:.0%} → p=0.948 기준 필요한 가속 s* = {critical_speedup(0.948, q):>6.2f}배")
# 출력: 반증선 90% → p=0.948 기준 필요한 가속 s* =   2.03배
# 출력: 반증선 80% → p=0.948 기준 필요한 가속 s* =   4.56배
# 출력: 반증선 70% → p=0.948 기준 필요한 가속 s* =   7.81배
# 출력: 반증선 60% → p=0.948 기준 필요한 가속 s* =  12.15배
# 출력: 반증선 50% → p=0.948 기준 필요한 가속 s* =  18.23배

# %% [markdown]
# ## 4단계 — 왜 분기마다 다시 재야 하나
#
# 위 계산은 전부 $p$와 $s$를 **알고 있다**고 가정했습니다. 실제로는 둘 다 모릅니다.
#
# - $p$는 모델 교체·컨텍스트 길이·조회 경로 변경으로 계속 움직입니다.
# - $s$는 "지난 분기 대비 모델 구간 시간이 몇 배 짧아졌나"로만 알 수 있습니다.
#
# 그래서 실무에서 재는 것은 $s$가 아니라 **분기별 구간 시간 자체**이고,
# $p'$는 그 측정값에서 바로 나옵니다. 아래는 모델 구간이 분기마다 30%씩
# 짧아지고 모델 아닌 구간은 그대로일 때의 시뮬레이션입니다.

# %%
model_ms, rest_ms = 1900.0, 105.0  # 33장 실측 근처: 94.8% 가 되는 조합
decay = 0.70                        # 분기마다 모델 구간이 30% 짧아진다고 가정

print(f"{'분기':<5}{'모델(ms)':>10}{'기타(ms)':>10}{'전체(ms)':>10}{'모델 비중':>10}  판정")
crossed = None
for qtr in range(9):
    total = model_ms + rest_ms
    share = model_ms / total
    verdict = "반증" if share < 0.60 else "유지"
    if crossed is None and share < 0.60:
        crossed = qtr
    print(f"Q{qtr:<4}{model_ms:>10.1f}{rest_ms:>10.1f}{total:>10.1f}{share:>10.1%}  {verdict}")
    model_ms *= decay
print(f"\n60% 를 처음 깬 분기: Q{crossed}  (누적 가속 {1 / decay**crossed:.1f}배)")
# 출력: 분기     모델(ms)  기타(ms)  전체(ms)     모델 비중  판정
# 출력: Q0        1900.0     105.0    2005.0     94.8%  유지
# 출력: Q1        1330.0     105.0    1435.0     92.7%  유지
# 출력: Q2         931.0     105.0    1036.0     89.9%  유지
# 출력: Q3         651.7     105.0     756.7     86.1%  유지
# 출력: Q4         456.2     105.0     561.2     81.3%  유지
# 출력: Q5         319.3     105.0     424.3     75.3%  유지
# 출력: Q6         223.5     105.0     328.5     68.0%  유지
# 출력: Q7         156.5     105.0     261.5     59.8%  반증
# 출력: Q8         109.5     105.0     214.5     51.1%  반증
#
# 출력: 60% 를 처음 깬 분기: Q7  (누적 가속 12.1배)

# %% [markdown]
# 시뮬레이션이 말해 주는 것.
#
# - 분기마다 **30%씩** 빨라지는데도 Q6까지는 68%로 "여전히 지배 구간"입니다.
#   비중은 초반에 거의 안 움직입니다. **한 분기만 재면 아무 일도 없는 것처럼 보입니다.**
# - 그러다 Q6→Q7에서 68% → 59.8%로 한 번에 넘어갑니다.
#   추세를 미리 보고 있지 않으면 **넘어간 뒤에 알게 됩니다.**
# - 누적 가속 12.1배 — 앞에서 역산한 $s^{*}=12.15$와 정확히 맞습니다.
#
# 이게 "분기마다 구간별 시간을 다시 재라"의 이유입니다. 반증 조건은 판정만
# 하는 게 아니라 **언제 판정이 뒤집힐지 미리 보여 주는 장치**입니다.
# 그리고 $1-p$(모델 아닌 구간, 위에서 105ms 고정)를 줄이는 일을 안 하면
# 모델이 아무리 빨라져도 전체 지연은 214.5ms에서 더 못 내려갑니다.

# %%
# 아래로의 한계: s → ∞ 일 때
print(f"s=∞ 일 때 전체 지연 = {rest_ms:.1f}ms (모델 아닌 구간이 하한)")
print(f"s=∞ 일 때 모델 비중 = {new_share(0.948, 1e9):.4%}")
print(f"p=0.948 에서 이론상 최대 전체 단축 = {1 / (1 - 0.948):.1f}배")
# 출력: s=∞ 일 때 전체 지연 = 105.0ms (모델 아닌 구간이 하한)
# 출력: s=∞ 일 때 모델 비중 = 0.0000%
# 출력: p=0.948 에서 이론상 최대 전체 단축 = 19.2배

# %% [markdown]
# ## 5단계 — 여러 $p$에 대한 $s$–$p'$ 곡선

